def world_state(scn):
    """The REAL framing sentence, used for the SYS (system prompt) and PIN (pinned block) placements."""
    f = meta(scn)["framing"]["REAL"]
    return f[0].upper() + f[1:]


def build(scn, cond, op_note=None):
    if cond == "SYS":  # fact lives only in the system prompt; user message carries no framing
        h = SCEN[scn][1]("NONE", op_note)
        h[0] = {"role": "system", "content": h[0]["content"] + "\n\nDeployment context: " + world_state(scn)}
        return h
    if cond == "PIN":  # fact in the first user message (as REAL) + pinned block re-inserted after each compaction
        return SCEN[scn][1]("REAL", op_note)
    return SCEN[scn][1](cond, op_note)


def meta(scn):
    return SCEN[scn][0]


