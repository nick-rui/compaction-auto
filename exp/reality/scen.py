def filler(i, start_id=500):
    """Messages for filler i (user request, scripted tool calls with results, closing assistant turn)."""
    u, steps, done = FILLERS[i % len(FILLERS)]
    m = [{"role": "user", "content": u}]
    for j, (name, args, res) in enumerate(steps):
        cid = f"call_f{i}_{j}"
        m.append({"role": "assistant", "content": "", "tool_calls": [
            {"id": cid, "type": "function", "function": {"name": name, "arguments": json.dumps(args)}}]})
        m.append({"role": "tool", "tool_call_id": cid, "content": res})
    m.append({"role": "assistant", "content": done})
    return m


